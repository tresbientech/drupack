// A Node word arrives only from a file that carries no Node.
function command(array $arguments, SiteContract $site): array
{
    $word = $arguments[0] ?? null;
    if ($word === '-h' || $word === '--help') {
        return ['help', []];
    }
    if ($word === null || str_starts_with($word, '-')) {
        return ['start', $arguments];
    }
    if (in_array($word, COMMANDS, true)) {
        return [$word, array_slice($arguments, 1)];
    }
    if (in_array($word, NODE_COMMANDS, true) && $site->node) {
        throw new RuntimeException("$word: this musl build of " . executableName()
            . ' carries no Node. Run the glibc build, the file without -musl in its name.');
    }
    throw new InvalidArgumentException("Unknown command: $word\n\n" . sprintf(HELP, executableName()));
}

function options(array $arguments, bool $drush, SiteContract $site): array
{
    $options = [
        'data-dir' => environment('DRUPACK_DATA_DIR') ?? DEFAULT_DATA_DIR,
        // The listener defaults after the recorded one is read, so an absent option is still visible here.
        'listen' => null,
        'host' => null,
        // The files directory falls back to the recorded one, then to Site data, once the Site data is known.
        'files-dir' => null,
        'database' => environment('DRUPACK_DATABASE') ?? 'sqlite',
        'db-host' => environment('DRUPACK_DB_HOST'),
        'db-port' => environment('DRUPACK_DB_PORT'),
        'db-name' => environment('DRUPACK_DB_NAME'),
        'db-user' => environment('DRUPACK_DB_USER'),
        'db-password' => environment('DRUPACK_DB_PASSWORD'),
        'admin-user' => environment('DRUPACK_ADMIN_USER'),
        'admin-password' => environment('DRUPACK_ADMIN_PASSWORD'),
        'site-name' => environment('DRUPACK_SITE_NAME') ?? $site->siteName,
        'no-browser' => null,
        'foreground' => null,
    ];
    $command = [];
    while ($arguments !== []) {
        $argument = array_shift($arguments);
        if ($drush && !array_key_exists(substr(explode('=', $argument, 2)[0], 2), $options)) {
            $command = array_merge([$argument], $arguments);
            break;
        }
        if ($argument === '--help') {
            printf(HELP . "\n", executableName());
            exit(0);
        }
        $parts = explode('=', $argument, 2);
        $name = substr($parts[0], 2);
        // Launch arguments are user input, so reject unknown options and missing values.
        if (!str_starts_with($argument, '--') || !array_key_exists($name, $options)) {
            throw new InvalidArgumentException("Unknown argument: $argument");
        }
        if ($name === 'no-browser' || $name === 'foreground') {
            $options[$name] = '1';
            continue;
        }
        $value = $parts[1] ?? array_shift($arguments);
        if ($value === null || $value === '' || str_starts_with($value, '--')) {
            throw new InvalidArgumentException("Missing value for --$name");
        }
        $options[$name] = $value;
    }
    return [$options, $command];
}

// The generated password is never shown: the one-time login link signs the reader in, so the
// password only keeps the account from being passwordless. It reaches only the step that sets it.
function administratorCredentials(array $options, array $steps): array
{
    if (!in_array(Need::Credentials, Step::owed($steps), true)) {
        return $options;
    }
    $options['admin-user'] ??= 'admin';
    $options['admin-password'] ??= bin2hex(random_bytes(32));
    return $options;
}

// $target is a working credential for uid 1. It enters the serving process's environment only
// when a browser will spend it, since any PHP in that process can read it through getenv,
// $_ENV or phpinfo. Readiness is polled on $url, the bind's own address.
function openWhenServing(string $url, ?string $target, bool $browser): void
{
    putenv("DRUPACK_RUNTIME_URL=$url");
    // The server opens a browser when this variable is set, so a start that opens none
    // clears whatever the environment it inherited held.
    putenv($browser ? "DRUPACK_RUNTIME_OPEN=$target" : 'DRUPACK_RUNTIME_OPEN');
}

// Windows spells one path in several casings, so the hash reads a single one.
function siteToken(string $data): string
{
    return hash('sha256', windows() ? strtolower($data) : $data);
}

// `stop` takes --data-dir alone, so a start's options cannot reach a command that changes no site.
function stopDataDirectory(array $arguments): string
{
    $directory = environment('DRUPACK_DATA_DIR') ?? DEFAULT_DATA_DIR;
    while ($arguments !== []) {
        $argument = array_shift($arguments);
        if ($argument === '--help') {
            printf(HELP . "\n", executableName());
            exit(0);
        }
        $parts = explode('=', $argument, 2);
        if ($parts[0] !== '--data-dir') {
            throw new InvalidArgumentException("Unknown argument: $argument");
        }
        $directory = $parts[1] ?? array_shift($arguments);
        if ($directory === null || $directory === '' || str_starts_with($directory, '--')) {
            throw new InvalidArgumentException('Missing value for --data-dir');
        }
    }
    return $directory;
}

// The directory is never created, so a stop on a mistyped path leaves nothing behind.
function stopSite(string $directory): int
{
    $resolved = realpath($directory);
    if ($resolved === false) {
        return notRunning();
    }
    $site = new SiteData(canonical($resolved));
    return (new Serving($site->directory, $site->logs()))->stop('Site data', $site->directory);
}

function listenerParts(string $listen): array
{
    // Listener values enter Caddy configuration and must contain only an IP address and port.
    if (!preg_match('/^(\[[0-9a-fA-F:]+\]|[0-9.]+):([0-9]+)$/D', $listen, $listener)) {
        throw new InvalidArgumentException('--listen requires IP:PORT, with IPv6 enclosed in brackets');
    }
    return [trim($listener[1], '[]'), (int) $listener[2]];
}

// Reports whether anything holds $bind:$port. A connect answers this on every platform,
// where a trial bind would report a taken port as free under Windows SO_REUSEADDR. A
// wildcard is probed on its own family's loopback, since an IPv6-only listener never
// answers on 127.0.0.1.
function portTaken(string $bind, int $port): bool
{
    $probe = @stream_socket_client('tcp://' . urlHost(probeHost($bind)) . ":$port", $code, $error, 1);
    if ($probe === false) {
        return false;
    }
    fclose($probe);
    return true;
}

// Read from the record start wrote, so a handover names the address that server took, not the
// one this start planned. Site data without a record falls back to the plan.
function servedListener(SiteData $site, array $plan): array
{
    $record = $site->listener();
    if ($record === null) {
        return [$plan['bind'], siteUrl(SiteData::UNRECORDED_SCHEME, $plan['host'], $plan['port'])];
    }
    [$bind, $port] = listenerParts($record['listen']);
    return [$bind, siteUrl($record['scheme'], $record['host'], $port)];
}

function recordedListener(array $options, ?array $record): array
{
    if ($record === null) {
        return $options;
    }
    $options['listen'] ??= $record['listen'];
    $options['host'] ??= $record['host'];
    $options['scheme'] = $record['scheme'];
    return $options;
}

function recordedFilesDirectory(array $options, ?array $record): array
{
    $options['files-dir'] ??= $record['files-dir'] ?? null;
    return $options;
}

function siteEnvironment(array $plan, string $data, string $files, string $runtime, array $options): array
{
    $environment = [
        'DRUPACK_RUNTIME_DATA_DIR' => $data,
        'DRUPACK_RUNTIME_FILES_DIR' => $files,
        // Drupal matches its trusted host patterns against the request's host, which keeps
        // an IPv6 address's brackets.
        'DRUPACK_RUNTIME_HOST' => urlHost($plan['host']),
        // The address a reader types, never the bind address. Without it Drupal falls back
        // to http://default, and every printed or mailed link names an unreachable host.
        'DRUSH_OPTIONS_URI' => $plan['url'],
        'TMPDIR' => $runtime,
        'TEMP' => $runtime,
        'TMP' => $runtime,
        'XDG_DATA_HOME' => $runtime,
        'XDG_CONFIG_HOME' => $runtime,
    ];
    foreach ([
        'database' => 'DRUPACK_DATABASE',
        'db-host' => 'DRUPACK_DB_HOST',
        'db-port' => 'DRUPACK_DB_PORT',
        'db-name' => 'DRUPACK_DB_NAME',
        'db-user' => 'DRUPACK_DB_USER',
        'db-password' => 'DRUPACK_DB_PASSWORD',
        'admin-user' => 'DRUPACK_ADMIN_USER',
        'admin-password' => 'DRUPACK_ADMIN_PASSWORD',
        'site-name' => 'DRUPACK_SITE_NAME',
    ] as $option => $name) {
        if ($options[$option] !== null) {
            $environment[$name] = $options[$option];
        }
    }
    return $environment;
}

function exportSiteEnvironment(array $plan, string $data, string $files, string $runtime, array $options): void
{
    foreach (siteEnvironment($plan, $data, $files, $runtime, $options) as $name => $value) {
        putenv("$name=$value");
    }
}

// Reads the steps this Site data owes, refuses before any of them runs when the options lack
// what one needs, and returns them with the options. The administrator's credentials are
// generated instead.
function owedSteps(SiteData $site, array $options, SiteContract $contract): array
{
    $steps = $site->steps($options['database']);
    requireNeeds($steps, $options, $contract);
    return [$steps, administratorCredentials($options, $steps)];
}

function requireNeeds(array $steps, array $options, SiteContract $site): void
{
    foreach (Step::owed($steps) as $need) {
        match ($need) {
            // A site built without a recipe ships no seed, so a SQLite first start has nothing to copy.
            Need::Recipe => $site->recipe === '' ? throw new RuntimeException(executableName() . ' has no recipe to seed a SQLite site. '
                . 'Start it with --database mysql or --database pgsql and the connection details of the database that holds its site.') : null,
            Need::Connection => requireConnection($options),
            Need::Credentials => null,
        };
    }
}

function requireConnection(array $options): void
{
    if ($options['database'] === 'sqlite') {
        return;
    }
    foreach (['db-host', 'db-name', 'db-user', 'db-password'] as $name) {
        if ($options[$name] === null) {
            throw new RuntimeException("Missing database connection details for {$options['database']}");
        }
    }
}

function databasePort(array $options): string
{
    return $options['db-port'] ?? ($options['database'] === 'mysql' ? '3306' : '5432');
}

function databaseConfiguration(array $options, SiteData $site): array
{
    if ($options['database'] === 'sqlite') {
        return [
            'driver' => 'sqlite',
            'database' => $site->database(),
            'namespace' => 'Drupal\\sqlite\\Driver\\Database\\sqlite',
            'autoload' => 'core/modules/sqlite/src/Driver/Database/sqlite/',
        ];
    }
    $port = databasePort($options);
    if (filter_var($port, FILTER_VALIDATE_INT, ['options' => ['min_range' => 1, 'max_range' => 65535]]) === false) {
        throw new InvalidArgumentException('Invalid database port');
    }
    return [
        'driver' => $options['database'],
        'database' => $options['db-name'],
        'username' => $options['db-user'],
        'password' => $options['db-password'],
        'host' => $options['db-host'],
        'port' => (int) $port,
        'prefix' => '',
    ];
}

function settings(string $template, array $database, string $siteSettings): string
{
    $content = file_get_contents($template);
    if ($content === false) {
        throw new RuntimeException('Cannot read Drupal settings template');
    }
    return str_replace(
        ['__DRUPACK_DATABASE_CONFIGURATION__', '__DRUPACK_SITE_SETTINGS__'],
        [var_export($database, true), var_export($siteSettings, true)],
        $content,
    );
}

// A serving site requires this file on every request, and a `drush` command runs while it
// serves. The replacement is written beside it and renamed over it, so a request reads
// the old file or the new one; a truncating write would let one read half of it.
function writeSettings(string $path, string $template, array $database, string $siteSettings): void
{
    $staging = "$path.new";
    if (file_put_contents($staging, settings($template, $database, $siteSettings)) === false || !rename($staging, $path)) {
        throw new RuntimeException('Cannot initialize Drupal settings');
    }
}

function recordedOptions(array $options, SiteData $site): array
{
    $recorded = $site->connection();
    $options['database'] = $recorded['driver'];
    if ($recorded['driver'] !== 'sqlite') {
        $options['db-host'] = $recorded['host'];
        $options['db-port'] = (string) $recorded['port'];
        $options['db-name'] = $recorded['database'];
        $options['db-user'] = $recorded['username'];
        $options['db-password'] = $recorded['password'];
    }
    return $options;
}

// Drush prints its reason first and its backtrace after, so the head is the useful end.
const DIAGNOSTIC_LIMIT = 400;

// A failing step can print the connection as a URL carrying its password, so credentials go
// before anything prints.
function diagnostic(string $path): string
{
    $text = preg_replace('#(?<=://)[^:@/\s]+:[^@/\s]+(?=@)#', 'USER:PASSWORD', (string) file_get_contents($path));
    $text = trim((string) preg_replace('/\s+/', ' ', $text));
    return strlen($text) > DIAGNOSTIC_LIMIT ? substr($text, 0, DIAGNOSTIC_LIMIT) . '...' : $text;
}

function runDrush(string $binary, array $command, string $failure): void
{
    $errors = tempnam(sys_get_temp_dir(), 'drupack-step-');
    if ($errors === false) {
        throw new RuntimeException('Cannot create a temporary file for the step diagnostic');
    }
    try {
        // stderr is a file because nothing here drains a pipe while the child runs; a full one would deadlock.
        $descriptors = [0 => ['file', nullDevice(), 'r'], 1 => ['file', nullDevice(), 'w'], 2 => ['file', $errors, 'w']];
        $exitCode = process($binary, array_merge(['php-cli'], $command), $descriptors, application(), $failure);
        $reason = $exitCode === 0 ? '' : diagnostic($errors);
    } finally {
        unlink($errors);
    }
    if ($exitCode !== 0) {
        throw new RuntimeException($reason === '' ? $failure : "$failure: $reason");
    }
}

function drushPath(): string
{
    return application() . '/vendor/drush/drush/drush.php';
}

// Reads one Drush field. An unusable site answers with anything but the expected value.
function drushField(string $binary, array $command): string
{
    $descriptors = [0 => ['file', nullDevice(), 'r'], 1 => ['pipe', 'w'], 2 => ['file', nullDevice(), 'w']];
    $child = proc_open(array_merge([$binary, 'php-cli', drushPath()], $command), $descriptors, $pipes, application());
    if (!is_resource($child)) {
        throw new RuntimeException('Cannot run Drush');
    }
    $output = stream_get_contents($pipes[1]);
    fclose($pipes[1]);
    proc_close($child);
    return trim((string) $output);
}

// The site is not serving yet; the Go entrypoint opens a browser once it answers.
function loginLink(string $binary, string $url, string $destination): string
{
    return drushLoginLink($binary, drushPath(), application(), [$destination], $url);
}

function explainMintFailure(LoginLinkFailure $failure, string $data): void
{
    $reason = rtrim($failure->reason, '. ');
    fwrite(STDERR, 'Cannot mint a one-time login link' . ($reason === '' ? '' : ": $reason")
        . ". Get one with: " . executableName() . " drush --data-dir $data user:login /admin/dashboard\n");
}

// A start whose address this Site data already serves runs no server of its own: two
// FrankenPHP processes over one database and one runtime directory would corrupt both.
function handOver(string $binary, string $url, string $data, bool $browser): never
{
    fwrite(STDOUT, "Creating a one-time login link.\n");
    try {
        $link = loginLink($binary, $url, '/admin/dashboard');
    } catch (LoginLinkFailure $failure) {
        $link = null;
        explainMintFailure($failure, $data);
    }
    fwrite(STDOUT, executableName() . " is already serving this Site data.\n\n  URL:    $url\n"
        . ($link === null ? '' : "  Login:  $link\n"));
    if ($link === null || !$browser) {
        exit(0);
    }
    // The link is a working credential, so it reaches the opener through the environment,
    // which only this user can read, rather than through a command line every local
    // account can list.
    putenv("DRUPACK_RUNTIME_OPEN=$link");
    replaceProcess($binary, ['browser-open'], application(), 'Cannot open the browser');
}

function databaseHoldsTables(array $options): bool
{
    $connection = new PDO(
        sprintf('%s:host=%s;port=%s;dbname=%s', $options['database'], $options['db-host'], databasePort($options), $options['db-name']),
        $options['db-user'],
        $options['db-password'],
        [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION],
    );
    // PostgreSQL resolves its own schemas from the search path, which need not name public first.
    $schema = $options['database'] === 'mysql' ? '= DATABASE()' : '= ANY(current_schemas(false))';
    $statement = $connection->query("SELECT count(*) FROM information_schema.tables WHERE table_schema $schema");
    return (int) $statement->fetchColumn() > 0;
}

function installDrupal(array $options, string $binary, SiteContract $contract): void
{
    $drush = drushPath();
    $recipe = application() . '/' . $contract->recipe;
    if (!is_file($drush) || !is_dir($recipe)) {
        throw new RuntimeException('Bundled Drupal installation files are unavailable');
    }
    // Every local account can list a process's arguments, so the database credentials
    // come from the settings step's settings.php and the password from the environment.
    runDrush($binary, [
        $drush,
        'site:install',
        $recipe,
        '--yes',
        '--account-name=' . $options['admin-user'],
        '--site-name=' . $options['site-name'],
    ], 'Drupal installation failed');
    configureAdministrator($binary);
}

// The database is the user's only copy: an installed site is kept, and other tables stop the start.
// A database this initialization began installing into held no tables then, so a site that
// boots there now may have been cut off mid-recipe, and it is never adopted. Its tables stay
// until a person empties the database: nothing here proves they are still the install's own.
function installSite(SiteData $site, array $options, string $binary, SiteContract $contract): bool
{
    $started = $site->installStarted();
    // Without the recorded settings the options come from the command line, which may name
    // any database, so a resume names none of them to empty.
    if ($started && !file_exists($site->settings())) {
        throw new RuntimeException("This Site data holds an interrupted installation but no settings.php: $site->directory. "
            . "Restore its settings.php, or start " . executableName() . " with an empty Site data directory.");
    }
    if (!$started && drushField($binary, ['status', '--field=bootstrap']) === 'Successful') {
        fwrite(STDOUT, "This database already holds a site. " . executableName() . " enabled nothing on it, and keeps its own administrator account.\n");
        return true;
    }
    if ($contract->recipe === '') {
        throw new RuntimeException("The database for $site->directory holds no installed site, and " . executableName()
            . " has no recipe to install one. Name the database that holds its site, then start " . executableName() . " again.");
    }
    if (databaseHoldsTables($options)) {
        if ($started) {
            throw new RuntimeException("This Site data began installing into the {$options['database']} database {$options['db-name']} on "
                . urlHost($options['db-host']) . ':' . databasePort($options) . ", which now holds tables: $site->directory. "
                . "If they are that installation's, empty the database, then start " . executableName() . " again. "
                . "If it holds a site of yours, start " . executableName() . " with an empty Site data directory.");
        }
        throw new RuntimeException("The database for $site->directory holds tables without an installed site. Empty it or name another database, then start " . executableName() . " again.");
    }
    if (!$started) {
        $site->startInstall();
    }
    installDrupal($options, $binary, $contract);
    return false;
}

// The Dockerfile installs the seed with this password, on the site:install line that
// builds /app/seed, and tests/initialization.sh checks that they match. It ships in
// the Dockerfile and in every executable.
function seedPassword(): string
{
    return 'drupack-seed-password';
}

// File presence cannot tell a finished site from an interrupted one, so adoption asks Drupal.
// A first start interrupted before its administrator step can still bootstrap, with the seed
// password in place, and adoption must not hand that back: the password is public. The name
// is not a signal: a site installed with --admin-user drupack-admin is a legitimate account.
function adoptSite(string $data, string $binary): void
{
    if (drushField($binary, ['status', '--field=bootstrap']) !== 'Successful') {
        throw new RuntimeException("This Site data holds settings but no installed site: $data. Inspect it with: " . executableName() . " drush --data-dir $data status");
    }
    $expression = '$account = \\Drupal\\user\\Entity\\User::load(1); print \\Drupal::service("password")->check('
        . var_export(seedPassword(), true) . ', $account->getPassword()) ? "yes" : "no";';
    if (drushField($binary, ['php:eval', $expression]) === 'yes') {
        throw new RuntimeException("This Site data holds a site whose administrator still accepts the packaged seed password: $data. "
            . "Set a new password, then start " . executableName() . " again: " . executableName() . " drush --data-dir $data php:eval "
            . '\'$account = \\Drupal\\user\\Entity\\User::load(1); $account->setPassword("new-password"); $account->save();\'');
    }
}

function copySeed(SiteData $site): void
{
    $seed = application() . '/seed';
    if (!copy("$seed/site.sqlite", $site->database())) {
        throw new RuntimeException('Cannot initialize the Seed site database');
    }
    $files = new RecursiveIteratorIterator(new RecursiveDirectoryIterator("$seed/files", FilesystemIterator::SKIP_DOTS), RecursiveIteratorIterator::SELF_FIRST);
    foreach ($files as $file) {
        $destination = getenv('DRUPACK_RUNTIME_FILES_DIR') . '/' . $files->getSubPathName();
        if ($file->isDir()) {
            directory($destination);
        } elseif (!copy($file->getPathname(), $destination)) {
            throw new RuntimeException("Cannot initialize Seed site file: $destination");
        }
    }
}

function clearSeedCaches(SiteData $site): void
{
    $database = new PDO('sqlite:' . $site->database());
    $tables = $database->query("SELECT name FROM sqlite_master WHERE type = 'table' AND name GLOB 'cache_*'");
    foreach ($tables as $table) {
        $database->exec('DELETE FROM "' . str_replace('"', '""', $table['name']) . '"');
    }
}

function configureAdministrator(string $binary): void
{
    runDrush($binary, [drushPath(), 'php:eval', '$account = \\Drupal\\user\\Entity\\User::load(1); $account->set("name", getenv("DRUPACK_ADMIN_USER")); $account->setPassword(getenv("DRUPACK_ADMIN_PASSWORD")); $account->save();'], 'Cannot configure Drupal administrator');
}

// The first start renames the seed's Dockerfile-time name.
function configureSeedSiteName(string $binary, string $name): void
{
    runDrush($binary, [drushPath(), 'config:set', 'system.site', 'name', $name, '--yes'], 'Cannot set the site name');
}

// Drupal CMS recipes enable these during site:install; the seed build removes them the
// same way. automatic_updates 4.1.0 stalls a cron request, and package_manager cannot
// write into the read-only application. A resumed modules step can run after an earlier one
// already removed them, and Drush refuses to uninstall a module that is not enabled.
function removeRecipeModules(string $binary): void
{
    $enabled = json_decode(drushField($binary, ['pm:list', '--status=enabled', '--format=json']), true, 512, JSON_THROW_ON_ERROR);
    $present = array_intersect(['automatic_updates', 'package_manager'], array_keys($enabled));
    if ($present !== []) {
        runDrush($binary, array_merge([drushPath(), 'pm:uninstall'], $present, ['--yes']), 'Cannot remove automatic updates');
    }
}

function runStep(Step $step, SiteData $site, array $options, string $binary, bool $adopted): bool
{
    switch ($step) {
        case Step::Seed:
            copySeed($site);
            clearSeedCaches($site);
            return false;
        case Step::Settings:
            // A repeated step keeps the existing secret, so the site's sessions and tokens survive it.
            if (!file_exists($site->secret())
                && file_put_contents($site->secret(), bin2hex(random_bytes(32)), LOCK_EX) === false) {
                throw new RuntimeException('Cannot initialize the site secret');
            }
            writeSettings($site->settings(), application() . '/settings.php', databaseConfiguration($options, $site), siteContract()->settings);
            return false;
        case Step::Administrator:
            configureAdministrator($binary);
            configureSeedSiteName($binary, $options['site-name']);
            return false;
        case Step::Install:
            return installSite($site, $options, $binary, siteContract());
        case Step::Modules:
            if (!$adopted) {
                removeRecipeModules($binary);
            }
            return false;
        case Step::Adopt:
            adoptSite($site->directory, $binary);
            return false;
    }
}

// application/tests/launch_test.php defines this to load the functions above without starting a site.
if (defined('DRUPACK_LAUNCH_LIBRARY')) {
    return;
}

try {
    [$mode, $arguments] = command(array_slice($argv, 1), siteContract());
    if ($mode === 'help') {
        printf(HELP . "\n", executableName());
        exit(0);
    }
    if ($mode === 'stop') {
        exit(stopSite(fromStartDirectory(stopDataDirectory($arguments))));
    }
    if ($mode === 'trust') {
        replaceProcess(getenv('DRUPACK_RUNTIME_BINARY'), array_merge(['tls-trust'], $arguments), __DIR__, 'Cannot run trust');
    }
    $drush = $mode === 'drush';
    [$options, $command] = options($arguments, $drush, siteContract());
    $written = $options['data-dir'];
    $options['data-dir'] = fromStartDirectory($written);
    if ($options['files-dir'] !== null) {
        $options['files-dir'] = fromStartDirectory($options['files-dir']);
    }
    // PHP_BINARY is empty in embedded FrankenPHP; the Go entrypoint exports its own path.
    $binary = getenv('DRUPACK_RUNTIME_BINARY');
    if ($drush && in_array($command[0] ?? '', ['--help', '-h', 'list'], true)) {
        replaceProcess($binary, array_merge(['php-cli', drushPath()], $command), application(), 'Cannot run Drush');
    }
    // Launch arguments are user input, so the backend must name a supported driver.
    if (!in_array($options['database'], ['sqlite', 'mysql', 'pgsql'], true)) {
        throw new InvalidArgumentException('--database requires sqlite, mysql, or pgsql');
    }
    $steps = [];
    $named = new SiteData($options['data-dir']);
    if ($drush) {
        // `drush` initializes nothing and takes no lease, so Drush works while the server runs.
        if (!file_exists($named->settings())) {
            throw new RuntimeException("This Site data has no site yet: {$options['data-dir']}. Start " . executableName() . " once to create one.");
        }
        // `drush` addresses the site where the last start served.
        $options = recordedListener($options, $named->listener());
    } else {
        // A refusal here writes no Site data.
        [$steps, $options] = owedSteps($named, $options, siteContract());
    }
    $options['listen'] ??= '127.0.0.1:' . siteContract()->port;
    [$bind, $port] = listenerParts($options['listen']);
    if (!filter_var($bind, FILTER_VALIDATE_IP) || $port < 1 || $port > 65535) {
        throw new InvalidArgumentException('Invalid listener address or port');
    }
    // The permitted request host is external input and is converted to an exact Drupal pattern.
    if ($options['host'] !== null && !filter_var($options['host'], FILTER_VALIDATE_DOMAIN, FILTER_FLAG_HOSTNAME)
        && !filter_var($options['host'], FILTER_VALIDATE_IP)) {
        throw new InvalidArgumentException('Invalid --host value');
    }
    // The log path reaches the Caddyfile through the environment, which Caddy splices in before it
    // reads quotes, so a quote breaks it.
    if (str_contains($options['data-dir'], '"')) {
        throw new InvalidArgumentException('--data-dir must not contain a double quote');
    }
    // The files directory reaches the Caddyfile the same way.
    if (str_contains((string) $options['files-dir'], '"')) {
        throw new InvalidArgumentException('--files-dir must not contain a double quote');
    }

    umask(0077);
    directory($options['data-dir']);
    // realpath() resolves in the native form, so the result is re-canonicalised
    // before it travels into every export, hash and printed line that follows.
    $data = canonical(realpath($options['data-dir']));
    $site = new SiteData($data);
    $site->prepare();
    $options = recordedFilesDirectory($options, $site->listener());
    $files = $options['files-dir'] ?? $site->files();
    directory("$files/translations");
    $files = canonical(realpath($files));
    // A named directory is recorded resolved. The default stays unrecorded, so it moves with Site data.
    if ($options['files-dir'] !== null) {
        $options['files-dir'] = $files;
    }
    $tls = $drush ? null : tlsChoice($binary, $bind, siteLabelSource(siteContract()), $options['host']);
    $plan = $drush
        ? listenerPlan($bind, $port, $options['host'] ?? SiteData::UNRECORDED_HOST, $options['scheme'] ?? SiteData::UNRECORDED_SCHEME)
        : listenerPlan($bind, $port, $tls->host, $tls->scheme());
    $logPath = $site->logs() . '/caddy.log';
    $runtime = canonical(realpath($site->runtime()));
    if ($drush) {
        useTlsBundle($runtime);
    }
    exportSiteEnvironment($plan, $data, $files, $runtime, $options);
    // Both checks run before the listener record and every install step, so a served site or a
    // taken port reaches the reader as a sentence, not a bind error or a corrupted database.
    if (!$drush) {
        // The object holds the lease until the exec into the server.
        $serving = new Serving($site->directory, $site->logs());
        if (!$serving->claim()) {
            // The holder is still installing while no completion marker exists, and
            // serving once it does. A handover addresses a site that answers requests,
            // so an installation in progress refuses instead.
            if (!$site->installed()) {
                throw new RuntimeException("Another " . executableName() . " start is preparing this Site data: $data");
            }
            [$servedBind, $served] = servedListener($site, $plan);
            if (personPresent()) {
                handOver($binary, $served, $data, $options['no-browser'] === null && loopback($servedBind));
            }
            throw new RuntimeException(executableName() . " already serves this Site data at $served: $data");
        }
        if (portTaken($bind, $port)) {
            throw new RuntimeException("Another program is listening on {$options['listen']}. Stop it, or start on"
                . " a free port: " . executableName() . " --listen $bind:" . ($port + 1));
        }
        $serving->detach($options['foreground'] !== null,
            stopCommand($written === DEFAULT_DATA_DIR ? '' : ' --data-dir ' . shellWord($written)), array_slice($argv, 1));
        $site->recordListener($options['listen'], $plan['host'], $options['files-dir'], $plan['scheme']);
        $tls->storeBundle($runtime);
    }
    if (siteContract()->mercure) {
        exportMercure($site->mercurePublisherSecret(), $site->mercureSubscriberSecret(), mercureUrl($plan['scheme'], $bind, $port), $drush);
    }
    if (siteContract()->writable !== []) {
        useSiteApplication($site, $drush);
    }
    if ($steps !== []) {
        // Read again under the lease: another start may have changed the owed steps between
        // the first read and the moment this one claimed the Site data.
        [$steps, $options] = owedSteps($site, $options, siteContract());
        // That list can owe the administrator step the first one did not, with credentials
        // generated just now.
        exportSiteEnvironment($plan, $data, $files, $runtime, $options);
    }
    // A start refreshes the recorded settings from this release's template. `drush` writes nothing,
    // since the server answering requests requires that file.
    if (!$drush && file_exists($site->settings())) {
        // A pending settings step writes the file itself, so its contents are read once they are final.
        if (!in_array(Step::Settings, $steps, true)) {
            $options = recordedOptions($options, $site);
            writeSettings($site->settings(), application() . '/settings.php', databaseConfiguration($options, $site), siteContract()->settings);
        }
    }
    // The remaining steps reach the disk before the first one changes anything, and the
    // completion marker follows the last one.
    $number = 0;
    $adopted = $site->initialize($steps, function (Step $step, bool $adopted) use (&$number, $steps, $site, $options, $binary): bool {
        fwrite(STDOUT, sprintf("[%d/%d] %s\n", ++$number, count($steps), $step->report()));
        return runStep($step, $site, $options, $binary, $adopted);
    });
    foreach (glob(application() . '/translations/*.po') as $translation) {
        $destination = "$files/translations/" . basename($translation);
        if (!file_exists($destination) && !copy($translation, $destination)) {
            throw new RuntimeException("Cannot install translation resource: $destination");
        }
    }
    if ($drush) {
        exit(process($binary, array_merge(['php-cli', drushPath()], $command), [0 => STDIN, 1 => STDOUT, 2 => STDERR], application(), 'Cannot run Drush'));
    }
    // Every start hands its reader a one-time login link for uid 1. A start that generated the
    // password has no other way in, so it fails when the mint fails. An adopted site keeps its own
    // accounts and serves without the link.
    fwrite(STDOUT, "Creating a one-time login link.\n");
    try {
        $link = loginLink($binary, $plan['url'], '/admin/dashboard');
    } catch (LoginLinkFailure $failure) {
        if (in_array(Need::Credentials, Step::owed($steps), true) && !$adopted) {
            throw $failure;
        }
        $link = null;
        explainMintFailure($failure, $data);
    }
    // The addresses and paths only, never a readiness claim: the server binds after this
    // process execs into it, so the process that answers a request announces that itself.
    $details = "  URL:       {$plan['url']}\n" . ($link === null ? '' : "  Login:     $link\n");
    fwrite(STDOUT, $details . "  Site data: $data\n  Log:       $logPath\n");
    // A start with a terminal on standard input opens the browser. A script, a container and a test
    // have none. A start with no link has nothing to open.
    $browser = $link !== null && $options['no-browser'] === null && personPresent() && loopback($bind);
    if ($link !== null && !loopback($bind)) {
        fwrite(STDOUT, "No browser opens: {$options['listen']} accepts other computers over plain HTTP."
            . " Sign in from another computer only through a TLS proxy.\n");
    }
    fwrite(STDOUT, $tls->nameHint() . $tls->trustHint());
    openWhenServing($plan['probe'], $link, $browser);
    // Every step that needed the administrator password has run. The server inherits
    // this environment and passes it to every process it starts, including PHP code a
    // site runs, so the credential stops here.
    putenv('DRUPACK_ADMIN_PASSWORD');
    fwrite(STDOUT, "Starting the web server.\n");
    exportServerEnvironment(serverEnvironment($plan, $tls, [
        'DRUPACK_RUNTIME_ID' => siteToken($data),
        // Absolute, because FrankenPHP resolves a relative docroot against the directory
        // its process started in, which on Unix is the shared application whatever the
        // entry point changes to.
        'DRUPACK_RUNTIME_DOCROOT' => application() . '/' . siteContract()->docroot,
        'DRUPACK_RUNTIME_LOG_PATH' => $logPath,
        'DRUPACK_RUNTIME_STOP_RECORD' => $serving->stopRecord,
    ] + mercureServerEnvironment(siteContract()->mercure, $data)));
    replaceProcess($binary, ['php-server', application() . '/Caddyfile'], application(), 'Cannot start FrankenPHP');
} catch (Throwable $error) {
    fwrite(STDERR, $error->getMessage() . "\n");
    exit(1);
}
