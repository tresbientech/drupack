package main

import "fmt"

// siteHelp is the text a site's --help prints. %[1]s is the executable's name.
// TestHelpMatchesTheParserAndTheReference asserts its options against the
// parser's tables and docs/cli.md.
const siteHelp = `Usage: %[1]s [start] [OPTIONS]
       %[1]s drush [OPTIONS] DRUSH_COMMAND
       %[1]s export [OPTIONS] [DRUSH_OPTIONS]
       %[1]s php SCRIPT [ARGUMENTS]
       %[1]s php -r CODE
       %[1]s node|npm|npx [ARGUMENTS]
       %[1]s stop [--data-dir PATH]
       %[1]s trust [--uninstall]
       %[1]s clean [--dry-run]

Options:
  --data-dir PATH            Site data directory, ./data by default
  --listen IP:PORT           Listener address, 127.0.0.1 on the site's port by default
  --static-listen IP:PORT    Static listener, the site listener's address on the next port by default
  --host HOST                Permitted request host, by default the site's drupack.site host or localhost
  --files-dir PATH           Public files directory, files in Site data by default
  --database sqlite|mysql|pgsql
                             Database backend for a first start, sqlite by default
  --db-host HOST             Database server, for mysql and pgsql
  --db-port PORT             Database port, 3306 for mysql and 5432 for pgsql
  --db-name NAME             Database name, for mysql and pgsql
  --db-user NAME             Database user, for mysql and pgsql
  --db-password PASSWORD     Database password, for mysql and pgsql
  --admin-user NAME          Administrator account for a first start, admin by default
  --admin-password PASSWORD  Administrator password for a first start, generated by default
  --site-name NAME           Site name for a first start, the packaged site's name by default
  --no-browser               Do not open a browser
  --foreground               Serve in this terminal until a signal stops the site
  --version, --help

Commands:
  start                      Start the site, which a bare command does too
  drush                      Run a Drush command against the site
  export                     Export the site with Tome into the static directory,
                             for a site with a static export
  php                        Run a script or -r CODE on the bundled PHP, with no
                             PHP option
  stop                       Stop the site serving the Site data, for a site
                             another terminal started
  trust                      Install the local root that lets every Drupack site on
                             this computer serve HTTPS. It may ask for a password.
                             --uninstall removes it.
  node, npm, npx             Run the site's bundled Node release, for a site
                             that carries one
  clean                      Remove the unpacked runtimes, applications and Node
                             releases from the cache. --dry-run lists them and
                             removes nothing.

Examples:
  %[1]s
  %[1]s --data-dir ./site --listen 127.0.0.1:9000
  %[1]s --admin-user admin --admin-password 'choose-a-password'
  %[1]s drush --data-dir ./site status
  %[1]s drush --data-dir ./site user:login
  %[1]s export --data-dir ./site
  %[1]s clean --dry-run

docs/cli.md explains every option.`

// engineUsage is the text the engine's --help prints. %[1]s is the executable's
// name and %[2]s the default listener.
const engineUsage = `Usage: %[1]s [start] [DIR] [--listen IP:PORT] [--static-listen IP:PORT] [--foreground]
       %[1]s stop [DIR]
       %[1]s drush DRUSH_COMMAND
       %[1]s dr DRUPAL_COMMAND
       %[1]s export [DRUSH_OPTIONS]
       %[1]s php SCRIPT [ARGUMENTS]
       %[1]s php -r CODE
       %[1]s clean [--dry-run]
       %[1]s self-update [--check]
       %[1]s trust [--uninstall]

Serves the Drupal project in DIR, the working directory by default, with its
own settings, in the background. --foreground serves in this terminal until a
signal stops it. --listen defaults to %[2]s. A project whose composer.json sets
extra.drupack.static serves its Tome export, html beside the docroot, on
--static-listen, the listener's address on the next port by default.

Commands:
  start    Serve the project, which a bare command does too
  stop     Stop the server of the project in DIR
  drush    Run the Drush of the project holding the working directory
  dr       Run Drupal core's command line of that project
  export   Export that project with Tome at the static URL its last start
           served, or at the --uri given
  php      Run a script or -r CODE on the bundled PHP, with no PHP option
  clean    Remove the unpacked engine files and stopped folders' state
           from the cache
  self-update  Install the newest release over this file, or --check for one
  trust    Install the local root that lets every Drupack site on this
           computer serve HTTPS, or --uninstall it. It may ask for a password.

docs/cli.md explains every command.`

